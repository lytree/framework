using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Framework.DynamicApi.Generator;

/// <summary>
/// 把端点模型渲染为 Minimal API 注册代码。
/// 采用 <see cref="Microsoft.AspNetCore.Http.RequestDelegate"/> 重载 + 显式参数绑定，
/// 不依赖 RequestDelegateGenerator / 反射，因而可在 Native AOT 下运行。
/// 路由前缀、命名约定、结果包装开关仍由运行时 <c>DynamicApiOptions</c> 决定。
/// </summary>
internal static class EndpointEmitter
{
	private const string Resolver = "global::Framework.DynamicApi.DynamicApiRouteResolver";
	private const string Options = "global::Framework.DynamicApi.DynamicApiOptions";
	private const string Writer = "global::Framework.DynamicApi.MinimalApi.DynamicApiResponseWriter";
	private const string BodyReader = "global::Framework.DynamicApi.MinimalApi.DynamicApiBodyReader";

	internal static string RenderClass(ApiClassModel model)
	{
		var writer = new CodeWriter();

		writer.Line("// Generated by Framework.DynamicApi.Generator. Do not edit manually.");
		writer.Line("#nullable enable");
		writer.Line("using Microsoft.AspNetCore.Builder;");
		writer.Line("using Microsoft.AspNetCore.Http;");
		writer.Line("using Microsoft.Extensions.DependencyInjection;");
		writer.Line();
		writer.Line("namespace Framework.DynamicApi.Generated");
		writer.OpenBlock();

		writer.Line($"internal static class {model.ClassId}");
		writer.OpenBlock();

		writer.Line($"internal static void Map(global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder app, {Options} options)");
		writer.OpenBlock();

		writer.Line($"var controllerName = {Resolver}.FormatControllerName(" +
					$"\"{model.TypeName}\", options.RemoveControllerPostfixes, options.NamingConvention, options.GetRestFulControllerName);");

		var area = model.Area is null
			? "(options.DefaultAreaName ?? string.Empty)"
			: $"\"{Escape(model.Area)}\"";

		// 只有重载方法才需要把参数签名并入端点名：非重载方法保持 <类型全名>.<方法名> 的简洁形式，
		// 重载则必须区分，否则同名端点会让 ASP.NET Core 在启动阶段抛重复端点名异常。
		var overloadedNames = model.Methods
			.GroupBy(method => method.Name, StringComparer.Ordinal)
			.Where(group => group.Count() > 1)
			.Select(group => group.Key)
			.ToHashSet(StringComparer.Ordinal);

		for (var i = 0; i < model.Methods.Count; i++)
		{
			RenderMethod(writer, model, model.Methods[i], i, area, overloadedNames.Contains(model.Methods[i].Name));
		}

		writer.CloseBlock();
		writer.CloseBlock();
		writer.CloseBlock();

		return writer.ToString();
	}

	internal static string RenderAssemblyEntry(
		string assemblyName,
		IReadOnlyList<ApiClassModel> models,
		IReadOnlyList<string> modules)
	{
		var writer = new CodeWriter();

		writer.Line("// Generated by Framework.DynamicApi.Generator. Do not edit manually.");
		writer.Line("#nullable enable");
		writer.Line("using Microsoft.AspNetCore.Builder;");
		writer.Line("using Microsoft.AspNetCore.Http;");
		writer.Line();
		writer.Line($"namespace Framework.DynamicApi.Generated.{ModelBuilder.Sanitize(assemblyName)}");
		writer.OpenBlock();

		writer.Line("public static class DynamicApiEndpoints");
		writer.OpenBlock();

		writer.Line($"public static global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder MapDynamicApis(");
		writer.Indent();
		writer.Line($"this global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder app,");
		writer.Line($"{Options}? options = null)");
		writer.Unindent();
		writer.OpenBlock();

		writer.Line("global::System.ArgumentNullException.ThrowIfNull(app);");
		writer.Line($"options ??= new {Options}();");

		foreach (var model in models)
		{
			writer.Line($"global::Framework.DynamicApi.Generated.{model.ClassId}.Map(app, options);");
		}

		foreach (var module in modules)
		{
			writer.Line($"global::Framework.DynamicApi.Generated.{ModelBuilder.Sanitize(module)}.DynamicApiEndpoints.MapDynamicApis(app, options);");
		}

		writer.Line("return app;");

		writer.CloseBlock();
		writer.CloseBlock();
		writer.CloseBlock();

		return writer.ToString();
	}

	private static void RenderMethod(CodeWriter writer, ApiClassModel model, MethodModel method, int index, string area, bool overloaded)
	{
		writer.Line($"var actionName{index} = {Resolver}.FormatActionName(" +
					$"\"{method.Name}\", options.RemoveActionPostfixes, options.NamingConvention, options.GetRestFulActionName);");

		writer.Line($"var route{index} = {Resolver}.BuildRoute(options.DefaultApiPrefix, {area}, controllerName, actionName{index});");

		const string requestDelegate = "(global::Microsoft.AspNetCore.Http.RequestDelegate)(async (global::Microsoft.AspNetCore.Http.HttpContext __ctx) =>";

		writer.Line($"var endpoint{index} = {RenderMapCall(method.Verb, index, requestDelegate)}");
		writer.OpenBlock();

		writer.Line($"var __service = __ctx.RequestServices.GetRequiredService<global::{model.FullTypeName}>();");

		for (var i = 0; i < method.Parameters.Count; i++)
		{
			EmitBinding(writer, method.Parameters[i], index, i);
		}

		EmitInvocation(writer, method);

		writer.CloseBlock("));");

		writer.Line($"endpoint{index}.WithTags(controllerName{RenderTags(model)});");
		writer.Line($"endpoint{index}.WithName(\"{BuildEndpointName(model, method, overloaded)}\");");

		if (method.PayloadTypeName is not null)
		{
			var responseType = method.Return == ReturnKind.WrappedPayload
				? $"global::Framework.DynamicApi.Response.ResponseResul<{method.PayloadTypeName}>"
				: method.PayloadTypeName;

			writer.Line($"endpoint{index}.WithMetadata(new global::Microsoft.AspNetCore.Http.ProducesResponseTypeMetadata(200, typeof({responseType}), new[] {{ \"application/json\" }}));");
		}
	}

	private static void EmitBinding(CodeWriter writer, ParameterModel parameter, int methodIndex, int parameterIndex)
	{
		switch (parameter.Kind)
		{
			case ParameterKind.Services:
				writer.Line($"var {parameter.Name} = __ctx.RequestServices.GetRequiredService<{parameter.TypeName}>();");
				break;

			case ParameterKind.Body:
				EmitBodyBinding(writer, parameter, methodIndex, parameterIndex);
				break;

			case ParameterKind.Query:
				EmitQueryBinding(writer, parameter, methodIndex, parameterIndex);
				break;

			case ParameterKind.Route:
				EmitRouteBinding(writer, parameter, methodIndex, parameterIndex);
				break;
		}
	}

	private static void EmitQueryBinding(CodeWriter writer, ParameterModel parameter, int methodIndex, int parameterIndex)
	{
		var key = $"\"{parameter.Name.TrimStart('@')}\"";
		var suffix = $"{methodIndex}_{parameterIndex}";

		if (parameter.TypeName == "string")
		{
			if (parameter.IsNullable)
			{
				writer.Line($"string? {parameter.Name} = __ctx.Request.Query.TryGetValue({key}, out var __q{suffix}) ? __q{suffix}.ToString() : null;");
			}
			else
			{
				writer.Line($"if (!__ctx.Request.Query.ContainsKey({key})) {{ await {Writer}.WriteBadRequestAsync(__ctx, {key}); return; }}");
				writer.Line($"string {parameter.Name} = __ctx.Request.Query[{key}].ToString();");
			}

			return;
		}

		if (parameter.IsNullable)
		{
			writer.Line($"{parameter.TypeName}? {parameter.Name} = null;");
			writer.Line($"var __raw{suffix} = __ctx.Request.Query.TryGetValue({key}, out var __q{suffix}) ? __q{suffix}.ToString() : null;");
			writer.Line($"if (__raw{suffix} is {{ Length: > 0 }})");
			writer.OpenBlock();
			writer.Line($"if (!{parameter.TypeName}.TryParse(__raw{suffix}, out var __parsed{suffix})) {{ await {Writer}.WriteBadRequestAsync(__ctx, {key}); return; }}");
			writer.Line($"{parameter.Name} = __parsed{suffix};");
			writer.CloseBlock();

			return;
		}

		writer.Line($"if (!{parameter.TypeName}.TryParse(__ctx.Request.Query[{key}].ToString(), out var {parameter.Name})) {{ await {Writer}.WriteBadRequestAsync(__ctx, {key}); return; }}");
	}

	private static void EmitRouteBinding(CodeWriter writer, ParameterModel parameter, int methodIndex, int parameterIndex)
	{
		var key = $"\"{parameter.Name.TrimStart('@')}\"";
		var suffix = $"{methodIndex}_{parameterIndex}";

		if (parameter.TypeName == "string")
		{
			if (parameter.IsNullable)
			{
				writer.Line($"string? {parameter.Name} = __ctx.Request.RouteValues[{key}]?.ToString();");
			}
			else
			{
				writer.Line($"if (__ctx.Request.RouteValues[{key}] is null) {{ await {Writer}.WriteBadRequestAsync(__ctx, {key}); return; }}");
				writer.Line($"string {parameter.Name} = __ctx.Request.RouteValues[{key}]!.ToString()!;");
			}

			return;
		}

		if (parameter.IsNullable)
		{
			writer.Line($"{parameter.TypeName}? {parameter.Name} = null;");
			writer.Line($"var __raw{suffix} = __ctx.Request.RouteValues[{key}]?.ToString();");
			writer.Line($"if (__raw{suffix} is {{ Length: > 0 }})");
			writer.OpenBlock();
			writer.Line($"if (!{parameter.TypeName}.TryParse(__raw{suffix}, out var __parsed{suffix})) {{ await {Writer}.WriteBadRequestAsync(__ctx, {key}); return; }}");
			writer.Line($"{parameter.Name} = __parsed{suffix};");
			writer.CloseBlock();

			return;
		}

		writer.Line($"if (!{parameter.TypeName}.TryParse(__ctx.Request.RouteValues[{key}]?.ToString(), out var {parameter.Name})) {{ await {Writer}.WriteBadRequestAsync(__ctx, {key}); return; }}");
	}

	private static void EmitBodyBinding(CodeWriter writer, ParameterModel parameter, int methodIndex, int parameterIndex)
	{
		var suffix = $"{methodIndex}_{parameterIndex}";
		var bodyVariable = $"__body{suffix}";
		var key = $"\"{parameter.Name.TrimStart('@')}\"";

		writer.Line($"var {bodyVariable} = await {BodyReader}.ReadAsync<{parameter.TypeName}>(__ctx);");
		writer.Line($"if ({bodyVariable} is null) {{ await {Writer}.WriteBadRequestAsync(__ctx, {key}); return; }}");
		writer.Line(parameter.IsValueType
			? $"var {parameter.Name} = {bodyVariable}.Value;"
			: $"var {parameter.Name} = {bodyVariable}!;");
	}

	private static void EmitInvocation(CodeWriter writer, MethodModel method)
	{
		var arguments = string.Join(", ", method.Parameters.Select(ArgumentExpression));
		var call = $"__service.{method.Name}({arguments})";
		var awaited = method.ReturnsTaskLike ? "await " + call : call;

		switch (method.Return)
		{
			case ReturnKind.Void:
				writer.Line($"{awaited};");
				writer.Line($"{Writer}.WriteEmpty(__ctx);");
				break;

			case ReturnKind.Payload:
				writer.Line($"var __result = {awaited};");
				writer.Line($"await {Writer}.WriteAsync(__ctx, __result);");
				break;

			case ReturnKind.WrappedPayload:
				writer.Line($"var __result = {awaited};");
				writer.Line("if (options.FormatResult)");
				writer.OpenBlock();
				writer.Line($"await {Writer}.WriteWrappedAsync(__ctx, __result);");
				writer.CloseBlock();
				writer.Line("else");
				writer.OpenBlock();
				writer.Line($"await {Writer}.WriteAsync(__ctx, __result);");
				writer.CloseBlock();
				break;

			case ReturnKind.IResult:
				writer.Line($"var __result = {awaited};");
				writer.Line("if (__result is null) { __ctx.Response.StatusCode = 500; return; }");
				writer.Line("await __result.ExecuteAsync(__ctx);");
				break;
		}
	}

	private static string ArgumentExpression(ParameterModel parameter)
	{
		return parameter.Kind switch
		{
			ParameterKind.HttpContext => "__ctx",
			ParameterKind.HttpRequest => "__ctx.Request",
			ParameterKind.HttpResponse => "__ctx.Response",
			ParameterKind.ClaimsPrincipal => "__ctx.User",
			ParameterKind.CancellationToken => "__ctx.RequestAborted",
			_ => parameter.Name
		};
	}

	private static string RenderMapCall(string verb, int index, string requestDelegate)
	{
		return verb switch
		{
			"GET" => $"app.MapGet(route{index}, {requestDelegate}",
			"POST" => $"app.MapPost(route{index}, {requestDelegate}",
			"PUT" => $"app.MapPut(route{index}, {requestDelegate}",
			"DELETE" => $"app.MapDelete(route{index}, {requestDelegate}",
			"PATCH" => $"app.MapPatch(route{index}, {requestDelegate}",
			_ => $"app.MapMethods(route{index}, new[] {{ \"{verb}\" }}, {requestDelegate}"
		};
	}

	/// <summary>
	/// 生成端点名：默认 <c>{类型全名}.{方法名}</c>；重载方法附加参数类型签名以保持唯一。
	/// ASP.NET Core 要求端点名唯一，同名会在启动阶段抛 <see cref="InvalidOperationException"/>。
	/// </summary>
	private static string BuildEndpointName(ApiClassModel model, MethodModel method, bool overloaded)
	{
		var name = $"{model.FullTypeName}.{method.Name}";

		if (!overloaded || method.Parameters.Count == 0)
			return Escape(name);

		var signature = string.Join(",", method.Parameters.Select(parameter => parameter.TypeName.Replace("global::", string.Empty)));

		return Escape($"{name}({signature})");
	}

	private static string RenderTags(ApiClassModel model)
	{
		if (model.Groups.Count == 0)
			return string.Empty;

		var tags = string.Join(", ", model.Groups.Select(g => $"\"{Escape(g)}\""));

		return $", {tags}";
	}

	private static string Escape(string value)
	{
		return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
	}
}

/// <summary>
/// 带缩进管理的代码拼接器。
/// </summary>
internal sealed class CodeWriter
{
	private readonly StringBuilder _builder = new();
	private int _indent;

	public void Indent() => _indent++;

	public void Unindent() => _indent--;

	public void OpenBlock()
	{
		Line("{");
		_indent++;
	}

	public void CloseBlock()
	{
		_indent--;
		Line("}");
	}

	public void CloseBlock(string suffix)
	{
		_indent--;
		Line("}" + suffix);
	}

	public void Line(string text = "")
	{
		if (text.Length == 0)
		{
			_builder.Append('\n');
			return;
		}

		_builder.Append('\t', _indent);
		_builder.Append(text);
		_builder.Append('\n');
	}

	public override string ToString() => _builder.ToString();
}
